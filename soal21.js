const prompt = require('prompt-sync')({sigint:true})
let input = Number(prompt('Masukkan nilai : '))
if (input >= 90 && input <= 100 )
    console.log('Predikat nilai A')
else if (input >= 80 && input <= 89)
    console.log('Predikat nilai B')
else if (input >= 75 && input <= 79)
    console.log('Predikat nilai C')
else if (input >= 60 && input <= 74)
    console.log('Predikat nilai D')
else if (input < 60)
    console.log('Predikat nilai E')
else
    console.log('Nguawor kamu')